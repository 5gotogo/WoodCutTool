import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const routes = new Set(['/']);
for (const file of readdirSync(root).filter(name => /^sitemap.*\.xml$/.test(name))) {
  for (const match of readFileSync(resolve(root, file), 'utf8').matchAll(/<loc>([^<]+)<\/loc>/g)) {
    const url = new URL(match[1]);
    if (!url.pathname.endsWith('.xml')) routes.add(url.pathname);
  }
}
writeFileSync(resolve(root, 'functions/lib/conversion-routes.js'), `// Generated by scripts/build-conversion-routes.mjs; public routes only.\nexport const conversionRoutes = new Set(${JSON.stringify([...routes].sort(), null, 2)});\n`);
