import { readFileSync, writeFileSync } from "node:fs";
import { resolve, join } from "node:path";
import vm from "node:vm";
import { asyncNavigation } from "./async-navigation.mjs";

const root = resolve(import.meta.dirname, "..");
// Keep site-chrome.js as the authored source for links, CSS extraction and the
// reference renderer. Do not hand-maintain a second set of menu definitions.
const source = readFileSync(join(root, "assets/site-chrome.js"), "utf8");
const menuStart = source.indexOf("  function menuLink(");
const menuEnd = source.indexOf("  function header()");
const navStart = source.indexOf("  function initMegaNavigation()");
const navEnd = source.indexOf("  function initBackToTop()");
const initStart = source.lastIndexOf("\n  renderSiteChrome();");
if ([menuStart, menuEnd, navStart, navEnd, initStart].some(n => n < 0)) throw Error("Shared chrome boundaries changed");

const context = vm.createContext({ window: { location: { pathname: "/" } }, menuRoutes: {} });
const renderer = source.slice(0, initStart).replace(
  "const isCurrent = isActive(href, aliases);",
  "globalThis.menuRoutes[label] = [href, ...aliases]; const isCurrent = isActive(href, aliases);",
);
vm.runInContext(renderer + "\n globalThis.navMarkup = navLinks();\n})();", context);

export function siteMenuSource() {
  return `// Generated from assets/site-chrome.js; fetched only on menu intent.\n` +
    'const deferredMenus = new Map();\nfunction route() { return window.location.pathname || \"/\"; }\n' + source.slice(source.indexOf('  function isActive('), menuEnd) + `
export function menuFor(key) {
  deferredMenus.clear();
  navLinks();
  const menu = deferredMenus.get(key);
  return typeof menu === "function" ? menu() : menu;
}
`;
}

export function siteNavigationSource() {
  const shell = `  function navLinks() {
    const template = document.createElement("template");
    template.innerHTML = ${JSON.stringify(context.navMarkup)};
    const routes = ${JSON.stringify(context.menuRoutes)};
    for (const item of template.content.querySelectorAll(".nav-menu-item")) {
      const [href, ...aliases] = routes[item.dataset.menuKey];
      const active = isActive(href, aliases);
      item.classList.toggle("active", active);
      item.querySelector(".nav-trigger").classList.toggle("active", active);
    }
    return template.innerHTML;
  }

  let menusPromise = null, menuRetries = 0;
  function loadMenus() {
    if (!menusPromise) menusPromise = import("/assets/site-menus.js" + (menuRetries ? "?retry=" + menuRetries : ""))
      .catch(error => { menusPromise = null; menuRetries += 1; throw error; });
    return menusPromise;
  }

`;
  const navigation = asyncNavigation(source.slice(navStart, navEnd), `const menus = await loadMenus();
      const markup = menus.menuFor(item.dataset.menuKey || "");
      if (!markup) throw new Error("Missing navigation menu");
      if (!item.querySelector(".mega-menu")) item.insertAdjacentHTML("beforeend", markup);`);
  return "// Generated by scripts/build-site-navigation.mjs from assets/site-chrome.js.\n" +
    source.slice(0, menuStart).replace("  const deferredMenus = new Map();\n", "") + shell +
    source.slice(menuEnd, navStart) + navigation + source.slice(navEnd);
}

export function buildSiteNavigation() {
  for (const [file, contents] of [["site-navigation.js", siteNavigationSource()], ["site-menus.js", siteMenuSource()]]) {
    writeFileSync(join(root, "assets", file), contents);
    console.log(`Built ${file}: ${Buffer.byteLength(contents)} bytes.`);
  }
}
if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename) buildSiteNavigation();
