import assert from 'node:assert/strict';
import {existsSync,readFileSync} from 'node:fs';
import {sampleProject,calculate,validateProject,importProject,clearEvidence,exportCSV,renderSVG} from '../assets/door-installation-core.js';
import {guides} from './door-installation-data.mjs';
const p=sampleProject(),r=calculate(p);
assert.equal(r.holes,4);assert.deepEqual(r.issues,[]);
assert.deepEqual(r.doors[0].holes.map(h=>[h.x,h.y]),[[22.5,100],[22.5,616]]);
assert.deepEqual(r.doors[1].holes.map(h=>[h.x,h.y]),[[423.5,100],[423.5,616]]);
assert.equal(r.measured,0);assert.equal(r.doors[0].skin,6);
const one=(patch,shared={})=>({...p,...shared,doors:[{...p.doors[0],...patch}]});
assert.deepEqual(calculate(one({count:3})).doors[0].holes.map(h=>h.y),[100,358,616]);
assert.deepEqual(calculate(one({custom:[616,100,340]})).doors[0].holes.map(h=>h.y),[100,340,616]);
assert.ok(calculate(one({zones:[{from:117.5,to:150}]})).issues.some(s=>s.includes('touches')));
assert.equal(calculate(one({zones:[{from:117.5001,to:150}]})).issues.length,0);
assert.ok(calculate(one({custom:[10,616]})).issues.some(s=>s.includes('crosses')));
assert.ok(calculate(one({custom:[100,135]})).issues.some(s=>s.includes('overlap')));
assert.ok(calculate(one({custom:[100,100]})).issues.some(s=>s.includes('overlap')));
assert.ok(calculate(one({width:35})).issues.some(s=>s.includes('side edge')));
assert.ok(calculate(one({top:400,bottom:400})).issues.some(s=>s.includes('positive span')));
assert.ok(calculate(one({thickness:15})).issues.some(s=>s.includes('skin reserve')));
assert.equal(calculate(one({thickness:16})).issues.length,0);
assert.throws(()=>exportCSV(one({thickness:15})),/Resolve geometry/);
const gaps=calculate(one({gaps:[1.5,2.5,2.6,null]}));
assert.equal(gaps.measured,3);assert.equal(gaps.outside,1);
assert.deepEqual(gaps.doors[0].observations.map(g=>g?.delta??null),[-0.5,0.5,0.6000000000000001,null]);
assert.throws(()=>validateProject(one({gaps:['',null,null,null]})),/measured gap/);
for(const patch of [{count:2.5},{width:NaN},{id:''},{custom:[100]},{zones:[{from:20,to:10}]},{checks:{spec:'yes',coupon:false,swing:false}}])assert.throws(()=>validateProject(one(patch)));
assert.throws(()=>validateProject({...p,doors:[p.doors[0],p.doors[0]]}),/unique/);
assert.throws(()=>validateProject({...p,version:2}),/version/);
assert.throws(()=>validateProject({...p,doors:Array.from({length:31},(_,i)=>({...p.doors[0],id:'D'+i}))}),/1–30/);
const evidence=one({gaps:[2,2,2,2],checks:{spec:true,coupon:true,swing:true}});
assert.equal(importProject(evidence).doors[0].checks.spec,false);
assert.deepEqual(importProject(evidence).doors[0].gaps,[null,null,null,null]);
assert.equal(evidence.doors[0].checks.spec,true);
assert.equal(clearEvidence(evidence.doors[0]).checks.swing,false);
assert.deepEqual(validateProject(JSON.parse(JSON.stringify(p))),p);
assert.equal(calculate({...p,unit:'in'}).doors[0].holes[0].x,22.5);
const svg=renderSVG({...p,doors:[{...p.doors[0],id:'<script>alert(1)</script>'}]});
assert.ok(!svg.includes('<script>'));assert.ok(svg.includes('&lt;script&gt;'));assert.ok(svg.includes('100 mm scale check'));
assert.ok(exportCSV({...p,name:'=HYPERLINK("bad")'}).includes('"\'=HYPERLINK(""bad"")"'));
assert.equal(exportCSV(p).trim().split('\r\n').length,5);
assert.equal(new Set(guides.map(g=>g.slug)).size,12);
for(const g of guides){
  assert.equal(g.sections.length,4);
  assert.ok(g.sections.flat().join(' ').split(/\s+/).length>=270,`${g.slug}: substantive method required`);
  assert.ok(existsSync(new URL(`..${g.link}index.html`,import.meta.url)),g.link);
  const html=readFileSync(new URL(`../door-installation/${g.slug}/index.html`,import.meta.url),'utf8');
  assert.ok(html.includes('rel="canonical"'));assert.ok(html.includes(g.title));
  assert.ok(!html.includes('type="module" src="/assets/door-installation.js"'));
}
console.log('Door installation: geometry boundaries, coordinate conventions, gap observations, import/evidence isolation, export escaping and 12 editorial routes passed.');
