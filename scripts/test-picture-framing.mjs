import assert from "node:assert/strict";
import { planFrame, sample, frameCsv } from "../assets/picture-frame-core.js";
import { guides } from "./picture-framing-data.mjs";

const plan = planFrame(sample);
assert.deepEqual(plan.rabbet, [283, 358]);
assert.deepEqual(plan.sight, [265, 340]);
assert.deepEqual(plan.outside, [335, 410]);
assert.equal(plan.depthRemaining, 2);
assert.equal(plan.minimumOverlap, 6);
assert.equal(plan.ready, true);
assert.deepEqual(plan.sticks.map(stick => stick.members.map(part => part.long)), [[335, 410], [335, 410]]);
assert.deepEqual(plan.sticks.map(stick => stick.remaining), [19, 19]);
assert.equal(new Set(plan.sticks.flatMap(stick => stick.members.map(part => part.name))).size, 4);
assert.equal(planFrame({...sample, stick: 1538}).sticks.length, 1);
assert.equal(planFrame({...sample, stick: 1537}).sticks.length, 2);
assert.equal(planFrame({...sample, stick: 716}).sticks.length, 3);
assert.equal(planFrame({...sample, stick: 700}).sticks.length, 4);
assert.equal(planFrame({...sample, stick: 440}).sticks.length, 4);
assert.equal(planFrame({...sample, stick: 439.99}).sticks, null);
assert.equal(planFrame({...sample, stick: 781}).sticks.length, 2);
assert.equal(planFrame({...sample, reserve: 4}).ready, true);
assert.equal(planFrame({...sample, reserve: 4.1}).ready, false);
assert.equal(planFrame({...sample, clearance: 4.5}).ready, false);
assert.ok(planFrame({...sample, lip: sample.face}).error);
assert.ok(planFrame({...sample, width: 12}).error);
assert.ok(planFrame({...sample, stack: null}).error);
assert.ok(planFrame({...sample, gap: -1}).error);
assert.ok(planFrame({...sample, trim: sample.stick}).error);
assert.equal(frameCsv(planFrame({...sample, stick: 400}), "mm"), null);
assert.match(frameCsv(plan, "mm"), /1,Top,mm,335,283,265,45,19/);
assert.match(frameCsv(plan, "in"), /1,Top,in,13\.188976,11\.141732,10\.433071,45,0\.748031/);
assert.equal(frameCsv(plan, "mm").trim().split("\r\n").length, 5);
assert.equal(new Set(guides.map(guide => guide.slug)).size, 8);
console.log("Picture framing geometry, depth, bearing, stock allocation and CSV checks passed.");
